"""Play the real WebGL arcade through input events, without injected game state."""
import os
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

BASE = os.environ.get("VOYAGER_URL", "http://127.0.0.1:8765")
OUT = Path(os.environ.get("VOYAGER_ARTIFACTS", "/tmp/voyager-3d"))
OUT.mkdir(parents=True, exist_ok=True)

with sync_playwright() as p:
    browser = p.chromium.launch(headless=True)
    page = browser.new_page(viewport={"width": 1440, "height": 1000})
    errors = []
    page.on("pageerror", lambda error: errors.append(str(error)))
    page.on("console", lambda message: errors.append(message.text)
            if message.type == "error" and any(term in message.text for term in ["WebGL", "THREE.", "shader"]) else None)
    page.goto(BASE)
    page.wait_for_load_state("networkidle")
    expect(page.locator("#voyage-start")).to_be_enabled(timeout=30000)
    expect(page.locator("#voyage-canvas")).to_have_attribute("data-renderer", "webgl2")
    expect(page.locator("#voyage-canvas")).to_have_attribute("data-moons", "")
    assert page.locator("#voyage-canvas").evaluate("(el)=>Boolean(el.getContext('webgl2'))")
    assert page.locator("[data-tab]").count() == 0
    expect(page).to_have_title("Voyager 1: One Light-Day")
    page.screenshot(path=str(OUT / "3d-ready.png"), full_page=True)
    page.locator("#voyage-look").click()
    page.locator("#voyage-canvas").hover()
    page.mouse.down()
    page.mouse.move(900, 600, steps=8)
    page.mouse.up()
    page.locator("#voyage-look").click()
    expect(page.locator("#voyage-start")).to_be_visible()
    page.locator("#voyage-milestone").click()
    expect(page.locator("#chapter")).to_have_value("49")
    expect(page.locator("#voyage-level")).to_have_text("Level 50 / 50 · 100s · Milestone")
    page.locator("#voyage-start").click()
    expect(page.locator("#voyage-canvas")).to_have_attribute("data-moons", "")
    expect(page.locator("#voyage-coins")).not_to_have_text("0 / 45 records", timeout=12000)
    page.wait_for_function("Number(document.querySelector('#voyage-canvas').dataset.progress) > .141", timeout=25000)
    score_before_ufo = int(page.locator("#voyage-score").inner_text().replace(",", ""))
    expect(page.locator("#voyage-ufos")).to_have_text("1 / 6 UFOs", timeout=10000)
    score_after_ufo = int(page.locator("#voyage-score").inner_text().replace(",", ""))
    assert score_after_ufo - score_before_ufo >= 750
    page.screenshot(path=str(OUT / "3d-ufo.png"), full_page=True)
    page.keyboard.press("KeyE")
    expect(page.locator("#pulse-status")).to_have_text("Active")
    expect(page.locator("#voyage-pulse")).to_be_disabled()
    page.wait_for_timeout(2000)
    expect(page.locator("#pulse-status")).not_to_have_text("Active")
    old = float(page.locator("#voyage-canvas").get_attribute("data-offset-x"))
    page.keyboard.down("ArrowRight")
    page.wait_for_timeout(650)
    page.keyboard.up("ArrowRight")
    assert float(page.locator("#voyage-canvas").get_attribute("data-offset-x")) > old + 1
    page.keyboard.down("ArrowUp")
    page.wait_for_timeout(650)
    page.keyboard.up("ArrowUp")
    assert float(page.locator("#voyage-canvas").get_attribute("data-offset-y")) > 1
    page.keyboard.down("Space")
    page.wait_for_timeout(1000)
    page.keyboard.up("Space")
    assert page.locator("#voyage-charge").evaluate("el=>el.value") < .95
    page.keyboard.press("KeyP")
    expect(page.locator("#voyage-start")).to_have_text("Resume flight")
    page.wait_for_timeout(200)
    paused = page.locator("#voyage-canvas").get_attribute("data-progress")
    page.wait_for_timeout(500)
    assert page.locator("#voyage-canvas").get_attribute("data-progress") == paused
    page.locator("#voyage-start").click()
    page.locator("#sources-open").click()
    expect(page.locator("#sources-dialog")).to_be_visible()
    expect(page.locator("#sources-dialog")).to_contain_text("10:16:07 UTC")
    page.locator("#sources-close").click()
    expect(page.locator("#voyage-start")).to_have_text("Resume flight")
    page.locator("#voyage-start").click()
    page.wait_for_function("Number(document.querySelector('#voyage-canvas').dataset.progress) > .81", timeout=110000)
    page.screenshot(path=str(OUT / "3d-finish-approach.png"), full_page=True)
    # Finish a real run without jumping progress, calling engine helpers, or replacing state.
    expect(page.locator("#voyage-start")).to_have_text("Start new journey", timeout=115000)
    expect(page.locator("#voyage-progress")).to_have_attribute("value", "1")
    assert int(page.locator("#voyage-score").inner_text().replace(",", "")) > 0
    page.screenshot(path=str(OUT / "3d-result.png"), full_page=True)
    expect(page.locator("#voyage-overlay-title")).to_have_text("One light-day. Still going.")
    expect(page.locator("#voyage-date")).to_have_text("18 Nov 2026")
    expect(page.locator("#voyage-overlay-story")).to_contain_text("10:16:07 UTC")
    scores = page.evaluate("JSON.parse(localStorage.getItem('voyager1-years-scores-v1'))")
    assert scores["2026"] > 0
    assert page.locator("#voyage-canvas").get_attribute("data-journey-score") == str(scores["2026"])
    expect(page.locator("#level-transition")).not_to_be_visible()
    page.wait_for_timeout(4500)
    expect(page.locator("#chapter")).to_have_value("49")
    expect(page.locator("#voyage-start")).to_have_text("Start new journey")
    page.locator("#voyage-start").click()
    expect(page.locator("#chapter")).to_have_value("0")
    for chapter in ["2", "3", "35"]:
        page.locator("#chapter").select_option(chapter)
        expect(page.locator("#voyage-canvas")).to_have_attribute("data-moons", "")
        page.locator("#voyage-start").click()
        expected_moons = {"2": "Io,Europa,Ganymede,Callisto", "3": "Titan,Enceladus", "35": ""}
        if chapter != "35":
            expect(page.locator("#voyage-canvas")).to_have_attribute("data-moons", expected_moons[chapter], timeout=110000)
            page.locator("#voyage-pause").click()
        page.screenshot(path=str(OUT / f"3d-encounter-{chapter}.png"), full_page=True)
    page.reload()
    page.wait_for_load_state("networkidle")
    page.locator("#chapter").select_option("49")
    expect(page.locator("#voyage-best")).not_to_have_text("Best 0", timeout=30000)

    mobile = browser.new_page(viewport={"width": 390, "height": 844}, is_mobile=True, has_touch=True)
    mobile.on("pageerror", lambda error: errors.append(str(error)))
    mobile.goto(BASE)
    mobile.wait_for_load_state("networkidle")
    expect(mobile.locator("#voyage-start")).to_be_enabled(timeout=30000)
    assert mobile.evaluate("document.documentElement.scrollWidth <= innerWidth")
    mobile.locator("#voyage-start").click()
    expect(mobile.locator(".touch-flight")).to_be_visible()
    button = mobile.locator('[data-steer="right"]')
    button.scroll_into_view_if_needed()
    box = button.bounding_box()
    mobile.mouse.move(box["x"] + box["width"]/2, box["y"] + box["height"]/2)
    mobile.mouse.down()
    mobile.wait_for_timeout(600)
    mobile.mouse.up()
    assert float(mobile.locator("#voyage-canvas").get_attribute("data-offset-x")) > 1
    mobile.screenshot(path=str(OUT / "3d-mobile.png"))
    mobile.locator("#voyage-pulse").click()
    expect(mobile.locator("#pulse-status")).to_have_text("Active")
    mobile.close()

    embed = browser.new_page(viewport={"width": 1200, "height": 900})
    embed.goto(BASE)
    embed.set_content(f'<iframe title="Voyager" src="{BASE}" sandbox="allow-scripts allow-same-origin allow-popups" width="100%" height="820"></iframe>')
    frame = embed.frame_locator("iframe")
    expect(frame.locator("#voyage-start")).to_be_enabled(timeout=30000)
    frame.locator("#voyage-start").click()
    expect(frame.locator("#voyage-coins")).not_to_have_text("0 / 45 records", timeout=12000)
    embed.close()
    assert not errors, errors
    browser.close()
    print(f"PASS: real WebGL2, keyboard/touch, gold and moving UFO collection, pulse, boost, pause, full light-day run, final stop, saved yearly score, encounter-window moons, iframe. Screenshots: {OUT}")
